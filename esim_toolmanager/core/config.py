"""Configuration manager – settings file, PATH / env-var handling, backup."""

from __future__ import annotations

import logging
import shutil
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

__all__ = ["ConfigManager"]

logger = logging.getLogger("esim_toolmanager.core.config")

_DEFAULT_CONFIG_DIR = Path.home() / ".esim-toolmanager"
_DEFAULT_CONFIG_FILE = _DEFAULT_CONFIG_DIR / "config.yaml"


class ConfigManager:
    """Manage eSim Tool Manager configuration.

    Responsibilities:
    - Load / save a user configuration file (YAML).
    - Manage tool-specific paths and environment variables.
    - Generate shell scripts to export environment variables.
    - Back up configuration before making changes.

    Parameters
    ----------
    config_path:
        Path to the configuration file.  Created on first ``save()``.
    dry_run:
        If ``True``, mutating operations are logged but not executed.
    """

    def __init__(
        self,
        config_path: Optional[Path] = None,
        *,
        dry_run: bool = False,
    ) -> None:
        self.config_path = config_path or _DEFAULT_CONFIG_FILE
        self.dry_run = dry_run
        self._data: Dict[str, Any] = {
            "esim_version": "2.5",
            "tools": {},
            "env_vars": {},
            "paths": [],
        }

    # -- load / save ----------------------------------------------------------

    def load(self) -> None:
        """Load configuration from disk.  No-op if file doesn't exist."""
        if not self.config_path.exists():
            logger.debug("Config file not found, using defaults: %s", self.config_path)
            return
        logger.debug("Loading config: %s", self.config_path)
        with open(self.config_path, encoding="utf-8") as fh:
            loaded = yaml.safe_load(fh)
        if isinstance(loaded, dict):
            self._data.update(loaded)

    def save(self) -> None:
        """Persist configuration to disk."""
        if self.dry_run:
            logger.info("[DRY RUN] Would save config to %s", self.config_path)
            return
        self.config_path.parent.mkdir(parents=True, exist_ok=True)
        with open(self.config_path, "w", encoding="utf-8") as fh:
            yaml.dump(self._data, fh, default_flow_style=False, sort_keys=False)
        logger.info("Saved config to %s", self.config_path)

    # -- get / set ------------------------------------------------------------

    def get(self, key: str, default: Any = None) -> Any:
        """Return a top-level config value."""
        return self._data.get(key, default)

    def set(self, key: str, value: Any) -> None:
        """Set a top-level config value."""
        self._data[key] = value

    @property
    def data(self) -> Dict[str, Any]:
        """Return the full configuration dict (read-only view)."""
        return dict(self._data)

    # -- environment ----------------------------------------------------------

    def set_env_var(self, name: str, value: str) -> None:
        """Record an environment variable."""
        self._data.setdefault("env_vars", {})[name] = value
        logger.info("Set env var %s=%s", name, value)

    def add_path(self, path: str) -> None:
        """Add a directory to the managed PATH list (deduplicated)."""
        paths: List[str] = self._data.setdefault("paths", [])
        if path not in paths:
            paths.append(path)
            logger.info("Added to PATH: %s", path)

    def get_env_vars(self) -> Dict[str, str]:
        """Return all managed environment variables."""
        return dict(self._data.get("env_vars", {}))

    def get_paths(self) -> List[str]:
        """Return all managed PATH entries."""
        return list(self._data.get("paths", []))

    # -- env script generation ------------------------------------------------

    def export_env_script(self, shell: str = "bash") -> str:
        """Generate a shell snippet that exports managed env vars and PATH.

        Parameters
        ----------
        shell:
            ``"bash"`` / ``"zsh"`` / ``"fish"`` / ``"powershell"`` / ``"cmd"``.
        """
        lines: List[str] = []
        env_vars = self.get_env_vars()
        paths = self.get_paths()

        if shell in ("bash", "zsh", "sh"):
            lines.append("# Generated by esim-tm configure")
            for k, v in env_vars.items():
                lines.append(f'export {k}="{v}"')
            if paths:
                joined = ":".join(paths)
                lines.append(f'export PATH="{joined}:$PATH"')
        elif shell == "fish":
            lines.append("# Generated by esim-tm configure")
            for k, v in env_vars.items():
                lines.append(f"set -gx {k} \"{v}\"")
            for p in paths:
                lines.append(f"fish_add_path \"{p}\"")
        elif shell == "powershell":
            lines.append("# Generated by esim-tm configure")
            for k, v in env_vars.items():
                lines.append(f'$env:{k} = "{v}"')
            if paths:
                joined = ";".join(paths)
                lines.append(f'$env:PATH = "{joined};$env:PATH"')
        elif shell == "cmd":
            lines.append("REM Generated by esim-tm configure")
            for k, v in env_vars.items():
                lines.append(f"SET {k}={v}")
            if paths:
                joined = ";".join(paths)
                lines.append(f"SET PATH={joined};%PATH%")
        else:
            lines.append(f"# Unsupported shell: {shell}")

        return "\n".join(lines) + "\n"

    # -- backup ---------------------------------------------------------------

    def backup(self) -> Optional[Path]:
        """Create a timestamped backup of the current config file.

        Returns the backup path, or ``None`` if there is nothing to back up
        or in dry-run mode.
        """
        if not self.config_path.exists():
            logger.debug("No existing config to back up.")
            return None

        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        backup_path = self.config_path.with_suffix(f".{ts}.bak")

        if self.dry_run:
            logger.info("[DRY RUN] Would back up config to %s", backup_path)
            return None

        shutil.copy2(self.config_path, backup_path)
        logger.info("Backed up config to %s", backup_path)
        return backup_path

    # -- configure tool -------------------------------------------------------

    def configure_tool(self, tool_id: str, hints: Dict[str, Any]) -> None:
        """Apply configuration hints for a tool.

        *hints* is the ``config_hints`` dict from the manifest entry.
        """
        env_vars = hints.get("env_vars", {})
        paths = hints.get("paths", [])

        for k, v in env_vars.items():
            if v:
                self.set_env_var(k, v)

        for p in paths:
            if p:
                self.add_path(p)

        # Record that this tool has been configured
        self._data.setdefault("tools", {})[tool_id] = {
            "configured": True,
            "configured_at": datetime.now().isoformat(),
        }
